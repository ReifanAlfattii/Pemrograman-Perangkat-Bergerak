class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContent {
            DiceRollerTheme(dynamicColor = false) {
                DiceRollerApp()
            }
        }
    }
}

fun rollDice(random: Random = Random.Default): Int = random.nextInt(from = 1, until = 7)

fun diceResourceForResult(result: Int): Int = when (result) {
    1 -> R.drawable.dice_1
    2 -> R.drawable.dice_2
    3 -> R.drawable.dice_3
    4 -> R.drawable.dice_4
    5 -> R.drawable.dice_5
    else -> R.drawable.dice_6
}

@Preview(showBackground = true)
@Composable
fun DiceRollerApp() {
    DiceWithButtonAndImage(
        modifier = Modifier
            .fillMaxSize()
            .wrapContentSize(Alignment.Center)
    )
}

@Composable
fun DiceWithButtonAndImage(modifier: Modifier = Modifier) {
    var result by remember { mutableStateOf(1) }
    val imageResource = diceResourceForResult(result)

    Column(
        modifier = modifier,
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        Image(
            painter = painterResource(imageResource),
            contentDescription = result.toString()
        )
        Spacer(modifier = Modifier.height(16.dp))
        Button(
            onClick = { result = rollDice() },
            colors = ButtonDefaults.buttonColors(
                containerColor = Color(0xFF7548C5),
                contentColor = Color.White
            )
        ) {
            Text(
                text = stringResource(R.string.roll),
                fontSize = 24.sp
            )
        }
    }
}
